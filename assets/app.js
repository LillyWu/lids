// ========================================
// 1. Website pages
// ========================================

// Only page filenames need to be listed.
// All searchable text is loaded automatically.

const sitePages = [
  { title: 'Home', url: 'index.html' },
  { title: 'People', url: 'people.html' },
  { title: 'Publications', url: 'publications.html' },
  { title: 'Open Source', url: 'software.html' },
  { title: 'News', url: 'news.html' },
  { title: 'Openings', url: 'positions.html' }
];

// ========================================
// 2. Build search index dynamically
// ========================================

let searchIndexPromise = null;

async function buildSearchIndex() {

  const pages = await Promise.all(
    sitePages.map(async (page) => {

      try {
        const response = await fetch(page.url, {
          cache: 'no-cache'
        });

        if (!response.ok) {
          throw new Error(`Cannot load ${page.url}`);
        }

        const html = await response.text();

        // Parse HTML without displaying it
        const doc = new DOMParser().parseFromString(
          html,
          'text/html'
        );

        // Search only the page's main content
        const main = doc.querySelector('main');

        let text = main ? main.textContent : '';

        // The People page is generated by people.js.
        // Include its profile data in search.
        if (page.url === 'people.html') {

          const peopleResponse = await fetch(
            'assets/people.js',
            { cache: 'no-cache' }
          );

          if (peopleResponse.ok) {
            const source = await peopleResponse.text();

            // Extract profile fields from the existing
            // single-quoted people.js data objects.
            const fieldPattern =
              /\b(?:title|name|position|affiliation|email|research|bio)\s*:\s*'((?:\\.|[^'\\])*)'/g;

            const fields = Array.from(
              source.matchAll(fieldPattern),
              match => match[1]
            );

            text += ' ' + fields.join(' ');
          }
        }

        return {
          title: page.title,
          url: page.url,
          text: text.replace(/\s+/g, ' ').trim()
        };

      } catch (error) {
        console.warn('Search indexing error:', error);
        return null;
      }

    })
  );

  return pages.filter(Boolean);
}

// Load once, then reuse the search index
function getSearchIndex() {
  if (!searchIndexPromise) {
    searchIndexPromise = buildSearchIndex();
  }

  return searchIndexPromise;
}

// ========================================
// 3. Mobile navigation
// ========================================

const menu = document.querySelector('.menu-toggle');
const navigation = document.querySelector('#navigation');

if (menu && navigation) {

  menu.addEventListener('click', () => {
    const isOpen = navigation.classList.toggle('open');

    menu.setAttribute(
      'aria-expanded',
      String(isOpen)
    );
  });

}

// ========================================
// 4. Search interface
// ========================================

const searchToggle = document.querySelector('.search-toggle');
const searchPanel = document.querySelector('#search-panel');
const searchInput = document.querySelector('#search');
const searchResults = document.querySelector('#search-results');
const searchStatus = document.querySelector('#search-status');

if (
  searchToggle &&
  searchPanel &&
  searchInput &&
  searchResults &&
  searchStatus
) {

  // Open or close search panel
  searchToggle.addEventListener('click', () => {

    searchPanel.hidden = !searchPanel.hidden;

    const isOpen = !searchPanel.hidden;

    searchToggle.setAttribute(
      'aria-expanded',
      String(isOpen)
    );

    if (isOpen) {
      searchInput.focus();
    }

  });

  // Search dynamically
  async function performSearch() {

    const initialQuery = searchInput.value.trim();

    searchResults.replaceChildren();

    if (!initialQuery) {
      searchStatus.textContent = '';
      return;
    }

    searchStatus.textContent = 'Searching...';

    const pages = await getSearchIndex();

    // Use the latest input in case it changed
    // while pages were loading.
    const query = searchInput.value.trim().toLowerCase();

    searchResults.replaceChildren();

    if (!query) {
      searchStatus.textContent = '';
      return;
    }

    if (pages.length === 0) {
      searchStatus.textContent =
        'Unable to load pages. Please use a web server.';
      return;
    }

    // Support searches with multiple words
    const terms = query.split(/\s+/);

    const matches = pages.filter(page => {

      const content = (
        page.title + ' ' + page.text
      ).toLowerCase();

      return terms.every(term => content.includes(term));

    });

    // Display result count
    searchStatus.textContent = matches.length
      ? `${matches.length} matching ${
          matches.length === 1 ? 'page' : 'pages'
        }`
      : 'No matching pages found.';

    // Display matching pages
    matches.forEach(page => {

      const row = document.createElement('div');
      row.className = 'search-hit';

      const link = document.createElement('a');

      link.href = page.url;
      link.textContent = page.title;

      row.append(link);
      searchResults.append(row);

    });

  }

  searchInput.addEventListener('input', performSearch);

  // Close search with Escape
  searchInput.addEventListener('keydown', event => {

    if (event.key === 'Escape') {

      searchPanel.hidden = true;

      searchToggle.setAttribute(
        'aria-expanded',
        'false'
      );

      searchToggle.focus();
    }

  });

}

// ========================================
// 5. Optional photo gallery
// ========================================

const photoDialog = document.querySelector('#photo-dialog');

if (photoDialog) {

  const largePhoto = document.querySelector('#large-photo');
  const closePhoto = document.querySelector('#close-photo');

  document.querySelectorAll('.photo-button').forEach(button => {

    button.addEventListener('click', () => {

      if (!largePhoto) return;

      largePhoto.src = button.dataset.full;
      photoDialog.showModal();

    });

  });

  if (closePhoto) {
    closePhoto.addEventListener('click', () => {
      photoDialog.close();
    });
  }

  photoDialog.addEventListener('click', event => {

    if (event.target === photoDialog) {
      photoDialog.close();
    }

  });

}
